// One-off generator: converts simple-icons SVG files into a single
// React component file with inline paths (no runtime fetches).
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../public/img/brands/", import.meta.url);
const files = {
  apple: readFileSync(new URL("apple.svg", dir), "utf8"),
  dell: readFileSync(new URL("dell.svg", dir), "utf8"),
  hp: readFileSync(new URL("hp.svg", dir), "utf8"),
  lenovo: readFileSync(new URL("lenovo.svg", dir), "utf8"),
  asus: readFileSync(new URL("asus.svg", dir), "utf8"),
  acer: readFileSync(new URL("acer.svg", dir), "utf8"),
  msi: readFileSync(new URL("msi.svg", dir), "utf8"),
};

function parseSvg(markup) {
  const fill = (markup.match(/fill="(#[0-9A-Fa-f]{6})"/) || [])[1] || "currentColor";
  const paths = [...markup.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  return { fill, paths };
}

let out = `/* eslint-disable */
/**
 * Brand logos as inline SVG (simple-icons paths), so the brand row has zero
 * network dependencies. Generated by scripts/gen-brands.mjs.
 */

const BRAND_PATHS = {
`;

for (const [key, svg] of Object.entries(files)) {
  const { fill, paths } = parseSvg(svg);
  out += `  ${key}: { fill: "${fill}", d: [
`;
  for (const d of paths) out += `    "${d}",
`;
  out += `  ] },
`;
}

// Microsoft wordmark square (drawn by hand; removed from simple-icons)
out += `  microsoft: { fill: null, d: [] },
};

const MICROSOFT_SQUARES = [
  { x: 1, y: 1, color: "#F25022" },
  { x: 13, y: 1, color: "#7FBA00" },
  { x: 1, y: 13, color: "#00A4EF" },
  { x: 13, y: 13, color: "#FFB900" },
];

export default function BrandLogo({ id, size = 24, className = "" }) {
  if (id === "microsoft") {
    return (
      <svg viewBox="0 0 24 24" width={(size * 24) / 18} height={size} aria-hidden="true" focusable="false" className={className}>
        {MICROSOFT_SQUARES.map((sq) => (
          <rect key={sq.color} x={sq.x} y={sq.y} width="10" height="10" fill={sq.color} />
        ))}
      </svg>
    );
  }
  const brand = BRAND_PATHS[id];
  if (!brand) return null;
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} fill={brand.fill} aria-hidden="true" focusable="false" className={className}>
      {brand.d.map((d, index) => (
        <path key={index} d={d} />
      ))}
    </svg>
  );
}
`;

writeFileSync(new URL("../src/components/BrandLogos.jsx", import.meta.url), out);
console.log("BrandLogos.jsx written,", out.length, "bytes");
